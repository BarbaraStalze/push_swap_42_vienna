int	is_valid(char *str)
{
	int	i;

	i = 0;
	if (!((str[i] >= '0' && str[i] <= '9') || str[i] == '-')
		|| (str[0] == '0' && str[1] != 0))
		return (0);
	i++;
	while (str[i] != 0 && str[i] >= '0' && str[i] <= '9')
		i++;
	if (str[i] != 0 || i > 11)
		return (0);
	return (1);
}
